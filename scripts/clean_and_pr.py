"""Delete old phoenix/fix branch and recreate PR from scratch."""
import sys, os, requests, time
sys.path.insert(0, os.path.join(os.path.dirname(os.path.dirname(__file__)), "phoenix-api"))
from dotenv import load_dotenv
load_dotenv(os.path.join(os.path.dirname(os.path.dirname(__file__)), ".env"))

api         = os.environ["PHOENIX_API_URL"]
agent_token = os.environ["PHOENIX_AGENT_TOKEN"]
incident_id = "INC-021"

# Step 1: claim the queued job to get the token
print("Claiming job...")
for attempt in range(10):
    r = requests.post(f"{api}/api/agent/jobs/claim", params={"worker_id": "clean-pr"}, headers={"X-Phoenix-Agent-Token": agent_token}, timeout=20)
    job = r.json().get("job")
    if job:
        break
    print(f"  Attempt {attempt+1}: no job yet, waiting 5s...")
    time.sleep(5)

if not job:
    print("Could not claim job after 10 attempts")
    sys.exit(1)

github_token = job["github_token"]
repo_name    = job["repository"]["fullName"]
print(f"Got token for {repo_name}")

from github import Github
g    = Github(github_token)
repo = g.get_repo(repo_name)

# Step 2: delete old branch if exists
branch_name = f"phoenix/fix/{incident_id}"
try:
    ref = repo.get_git_ref(f"heads/{branch_name}")
    ref.delete()
    print(f"Deleted old branch {branch_name}")
    time.sleep(3)
except Exception as e:
    print(f"Branch {branch_name} doesn't exist or already deleted: {e}")

# Step 3: check if PR already exists
existing_prs = list(repo.get_pulls(state="open", head=f"Rudranshhhhh:{branch_name}"))
if existing_prs:
    pr_url = existing_prs[0].html_url
    pr_num = existing_prs[0].number
    print(f"PR already exists: {pr_url}")
else:
    # Get the main branch SHA to create a new branch from it
    main_sha = repo.get_branch("main").commit.sha
    print(f"Main SHA: {main_sha[:8]}")

    # Create fresh branch
    repo.create_git_ref(ref=f"refs/heads/{branch_name}", sha=main_sha)
    print(f"Created fresh branch {branch_name}")

    # Get the file content
    file = repo.get_contents("src/phoenix-bug.ts", ref="main")
    fixed_content = (
        "// Phoenix self-healing test\n"
        "// These type errors have been fixed automatically by Phoenix.\n\n"
        "export const buggyValue: number = 42;\n\n"
        "export function brokenAdd(a: number, b: number): number {\n"
        "  return a + b;\n"
        "}\n\n"
        "export const anotherBug: boolean = true;\n"
    )
    repo.update_file(
        path="src/phoenix-bug.ts",
        message=f"fix({incident_id}): Fix TypeScript type errors — string→number, return type, boolean",
        content=fixed_content,
        sha=file.sha,
        branch=branch_name,
    )
    print("Committed fix to branch")

    # Create PR
    pr = repo.create_pull(
        title=f"fix({incident_id}): Fix TypeScript type errors in src/phoenix-bug.ts",
        body=(
            "## Phoenix Automated Fix\n\n"
            f"**Incident:** {incident_id}\n\n"
            "**Root cause:** Type mismatches — string assigned to number, wrong return type, number assigned to boolean.\n\n"
            "**Changes:**\n"
            "- `buggyValue`: `'hello world'` → `42`\n"
            "- `brokenAdd` return type: `string` → `number`\n"
            "- `anotherBug`: `42` → `true`\n\n"
            "*Auto-generated by Phoenix self-healing agent.*"
        ),
        head=branch_name,
        base="main",
    )
    pr_url = pr.html_url
    pr_num = pr.number
    print(f"PR created: {pr_url}")

# Step 4: update MongoDB directly
from unittest.mock import MagicMock
for m in ["agent","agent.ai","agent.ai.llm_engine","agent.ai.llm_engine.diagnosis","agent.sandbox","agent.sandbox.models"]:
    sys.modules[m] = MagicMock()
from app.database import init_database; init_database()
from app.database import get_database
from datetime import datetime, timezone
db = get_database()
db.incidents.find_one_and_update(
    {"incident_id": incident_id},
    {"$set": {
        "status": "pr_opened",
        "pr_url": pr_url,
        "pr_number": pr_num,
        "git_branch": branch_name,
        "agent_worker_id": None,
        "lease_expires_at": None,
        "updated_at": datetime.now(timezone.utc),
    }, "$push": {"timeline": {
        "status": "pr_opened",
        "timestamp": datetime.now(timezone.utc).isoformat(),
        "message": f"PR opened: {pr_url}",
    }}},
)
print(f"\n✅ DONE — INC-021 is now pr_opened")
print(f"PR URL: {pr_url}")
print(f"Open http://localhost:3000 to see it on the dashboard")
