"""Create a GitHub PR for INC-021 directly."""
import sys, os, requests
sys.path.insert(0, os.path.join(os.path.dirname(os.path.dirname(__file__)), "phoenix-api"))
from dotenv import load_dotenv
load_dotenv(os.path.join(os.path.dirname(os.path.dirname(__file__)), ".env"))

from github import Github

api         = os.environ["PHOENIX_API_URL"]
agent_token = os.environ["PHOENIX_AGENT_TOKEN"]
incident_id = sys.argv[1] if len(sys.argv) > 1 else "INC-021"

# Get the GitHub token from a job claim
r = requests.post(
    f"{api}/api/agent/jobs/claim",
    params={"worker_id": "pr-creator"},
    headers={"X-Phoenix-Agent-Token": agent_token},
    timeout=15,
)
job = r.json().get("job")

if not job:
    # Incident may not be in queued state — get token from env
    github_token = os.environ.get("GITHUB_TOKEN", "")
    repo_name    = "Rudranshhhhh/Rudransh-portfolio"
    print("No queued job — using GITHUB_TOKEN from .env")
else:
    github_token = job["github_token"]
    repo_name    = job["repository"]["fullName"]
    incident_id  = job["incident"]["incident_id"]

print("Repo:", repo_name)
print("Creating PR for", incident_id)

g    = Github(github_token)
repo = g.get_repo(repo_name)

title = f"fix({incident_id}): Fix TypeScript type errors in src/phoenix-bug.ts"
body  = (
    "## Phoenix Automated Fix\n\n"
    f"**Incident:** {incident_id}\n\n"
    "**Root cause:** Type mismatches in variable declarations and function return types.\n\n"
    "**Changes made by Phoenix:**\n"
    "- `buggyValue: number` — changed from string literal to number\n"
    "- `brokenAdd` return type — fixed from `string` to `number`\n"
    "- `anotherBug: boolean` — changed from number literal to boolean\n\n"
    "*This PR was automatically generated by Phoenix self-healing agent.*"
)

try:
    pr = repo.create_pull(title=title, body=body, head=f"phoenix/fix/{incident_id}", base="main")
    print("PR created:", pr.html_url)
    pr_url = pr.html_url
    pr_num = pr.number
except Exception as e:
    if "already exists" in str(e).lower() or "A pull request already exists" in str(e):
        pulls = list(repo.get_pulls(state="open", head=f"Rudranshhhhh:phoenix/fix/{incident_id}"))
        if pulls:
            pr_url = pulls[0].html_url
            pr_num = pulls[0].number
            print("PR already exists:", pr_url)
        else:
            print("Error:", e)
            sys.exit(1)
    else:
        print("Error:", e)
        sys.exit(1)

# Report result back to Phoenix
result = {
    "status": "pr_opened",
    "message": f"PR opened: {pr_url}",
    "pull_request": {"pr_number": pr_num, "pr_url": pr_url, "head_branch": f"phoenix/fix/{incident_id}"},
}
